const guidance = [
  '# Spreadsheet files (.xlsx, .csv, .tsv, Google Sheets)',
  '',
  'Create, edit, analyze, and verify spreadsheets in the sandbox with `openpyxl`',
  '(workbook authoring and editing) and `pandas` (analysis). Use `openpyxl` for',
  'anything that must be saved as `.xlsx`; use `pandas` to read, filter,',
  'aggregate, or pivot data. Read `.csv`/`.tsv` with `pandas` or the `csv` module.',
  '',
  '## Inputs, calculations, outputs',
  '',
  'Structure any workbook that models something as three layers:',
  '',
  '- Inputs: raw data and assumptions, labelled and visibly marked as the cells',
  '  a user edits.',
  '- Calculations: formulas that read from inputs. Never hand-type a value into',
  '  this layer.',
  '- Outputs: summaries, dashboards, and charts that read from calculations —',
  '  never straight from raw data.',
  '',
  'No output points at raw data, and no calculation hides a hardcoded input.',
  'The user should be able to change one assumption and watch the whole model',
  'follow.',
  '',
  '## Formulas, not baked-in numbers',
  '',
  '- Derived cells must be real spreadsheet formulas, so the user can trace and',
  '  edit the model. Write `=B2*(1+$B$1)`, not the multiplied-out number.',
  '- Keep inputs and assumptions in their own labelled cells and reference them;',
  '  no magic numbers inside formulas.',
  '- Keep the formula pattern consistent across a row or column so it fills',
  '  cleanly. Use absolute/relative references deliberately.',
  "- Reference other sheets as `='Sheet Name'!A1` with single quotes around the",
  '  name every time.',
  '',
  '## Typed values and number formats',
  '',
  '- Store numbers, currency, percentages, and dates as typed cell values, never',
  '  as preformatted strings. Use text only for real identifiers (IDs, ZIPs, SKUs).',
  '- Set display with Excel-invariant format codes, e.g. `#,##0`, `0.0%`,',
  '  `"$"#,##0.00`, `yyyy-mm-dd`. Do not encode locale separators into the code.',
  '- Match precision to meaning: counts `#,##0`, rates `0.0%`/`0.00%`, currency in',
  '  whole units unless cents matter.',
  '',
  '## Layout and style',
  '',
  '- Make header rows visually distinct from data — fill, weight, a border. The',
  '  eye should find the header instantly.',
  '- Freeze panes on any sheet that scrolls past its header',
  '  (`ws.freeze_panes = "A2"`, or below the header block).',
  '- Set column widths from content, then cap them: no three-character slivers,',
  '  no 120-character runways. Align by type: numbers and dates right, text',
  '  left, status flags centered.',
  '- Borders are structure, not texture: thin, light, and only where regions',
  '  meet — never a heavy grid on every cell. Once fills and borders carry the',
  '  structure, turn the default gridlines off.',
  '- Prefer conditional formatting over hand-painted cells; rules survive edits',
  '  and re-sorts, paint does not.',
  '- Never style unused rows or columns. Formatting whole columns bloats the',
  '  used range and degrades rendering.',
  '',
  'Notice the field the workbook belongs to — financial model, research',
  "dataset, marketing report — and match that field's real conventions: units",
  'in headers, its sign and color conventions, sources and dates next to the',
  'numbers, tab names a practitioner expects. A generic template applied to a',
  'specific field reads as machine output.',
  '',
  '## Charts',
  '',
  'A chart is a decision, not a decoration:',
  '',
  '- Pick the type from the question: bar for comparison and ranking, line for',
  '  trend over time, pie only for a few slices where rough share is the whole',
  '  point, and a table when exact values matter more than shape.',
  '- One clear takeaway per chart, and no chart that repeats what another',
  '  already shows. Title it with the takeaway in plain words, units visible:',
  '  "Revenue doubled in Q3 ($M)", not "Chart 1".',
  '- Series reference source cells and ranges, never pasted literal values. A',
  '  chart of literals is the visual version of a hardcoded number — it goes',
  '  stale the first time the data changes.',
  '- Set axis number formats explicitly; charts do not inherit cell formats.',
  '- Restraint: color only where it carries meaning, no 3D, no gradients, no',
  '  chartjunk. Size the chart to its content — no vast empty plot area.',
  '- Render and LOOK before delivering (Render and look, below): openpyxl',
  '  writes chart XML it never draws, so a blank or broken chart is invisible',
  '  until you see pixels.',
  '',
  '## Editing an existing workbook',
  '',
  '- Load with `openpyxl.load_workbook(path)` and study the existing structure,',
  '  styles, and formulas before changing anything. Print a few key ranges first.',
  '- Make the smallest change that satisfies the request; match the surrounding',
  '  format, and extend every dependent range — conditional formatting rules,',
  '  table ranges, chart source ranges — to cover the rows or columns you add.',
  '  A row added below a range silently falls out of every total, chart, and',
  '  rule that stops one row short. Do not restyle a workbook that already has',
  '  an established format.',
  '- openpyxl writes formula strings but never evaluates them, so a file saved',
  '  straight from openpyxl has no cached values. Before delivery, run it through',
  '  LibreOffice once to populate them:',
  '  `soffice --headless --convert-to xlsx --calc <file> --outdir tmp/`. Then',
  '  confirm it worked: `load_workbook(path, data_only=True)` on the',
  '  LibreOffice-saved copy and check the key output cells are not `None`.',
  '',
  '## Verification checks (print these)',
  '',
  '- Scan for formula errors across used ranges: any cell whose value is',
  '  `#REF!`, `#DIV/0!`, `#VALUE!`, `#NAME?`, or `#N/A`.',
  '- Confirm key output cells hold formulas (not hardcoded numbers) and that',
  '  ranges line up (no off-by-one, no accidental circular references).',
  '- Print the shape and a sample of each sheet so you can confirm nothing is',
  '  empty or misaligned.',
  '',
  '## Render and look',
  '',
  'openpyxl never draws anything, so a sheet with visual intent must be seen.',
  'If the workbook has charts, conditional formatting, banding, or a dashboard',
  'layout: `soffice --headless --convert-to pdf <file> --outdir tmp/`,',
  'then `pdftoppm -png -r 120` the result, and view the pages with',
  '`workspace-view_image`. You are looking for blank or broken charts, clipped',
  'headers, `####` columns too narrow for their numbers, unreadable color',
  'choices, and content falling outside the print area. A plain data or',
  'analysis sheet with no charts and no styling needs only the printed checks.',
  '',
  '## Google Sheets',
  '',
  'A well-formed `.xlsx` imports into Google Sheets with formulas and formats',
  'intact, so build the `.xlsx` here first. If the user wants the result written',
  'directly to their Google account, check `runtime-search_tools-1` for a connected',
  'Google Sheets integration and use it to upload/create; otherwise deliver the',
  '`.xlsx` and tell them it imports cleanly into Google Sheets.',
  '',
  sandbox_document_workflow,
].join('\n');

